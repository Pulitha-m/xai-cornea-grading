-- Authentication & role-based access control schema.
-- Table names are prefixed/specific to avoid clashing with Supabase's own auth.users.

CREATE TABLE roles (
    id          INTEGER      PRIMARY KEY,
    name        VARCHAR(32)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

